async function run() {
  await mongoose.connect(env.mongodbUri);
  console.log('Connected:', mongoose.connection.name);

  let created = 0;
  let skipped = 0;
  for (const [slug, bn, en, division, lat, lng, overviewBn] of D) {
    const exists = await District.findOne({ slug });
    if (exists) {
      skipped++;
      continue; // never overwrite enriched districts (e.g., Sunamganj)
    }
    await District.create({
      slug,
      name: { bn, en },
      division,
      overview: { bn: overviewBn, en: '' },
      mapCenter: { lat, lng },
      zoom: 10,
      isLaunched: true,
      isVerified: false,
      features: { guideBooking: false, boatBooking: false, hotelBooking: false, transportBooking: false },
      emergency: { police: '৯৯৯ (জাতীয় জরুরি সেবা)', hospital: '', fireService: '৯৯৯' },
      stayTypesAvailable: [],
    });
    created++;
  }

  // Sunamganj: mark locally verified
  await District.updateOne({ slug: 'sunamganj' }, { $set: { isVerified: true } });

  const total = await District.countDocuments();
  console.log(`Created: ${created}, skipped existing: ${skipped}, total districts: ${total}`);
  console.log('Sunamganj marked isVerified=true');
  await mongoose.disconnect();
}

run().catch((err) => {
  console.error(err);
  process.exit(1);
});
